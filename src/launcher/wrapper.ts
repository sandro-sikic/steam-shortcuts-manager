import { chmod, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { configDir } from '../config.js';
import type { Game, UriLaunch } from '../types.js';

/** What the Steam shortcut should run. */
export interface ShortcutTarget {
  exe: string;
  startDir?: string;
  launchOptions?: string;
}

const MAX_WAIT_SECONDS = 120;

/** Where wrapper scripts are kept: `<config dir>/launchers`. */
export function wrapperDir(platform: NodeJS.Platform, home: string, env: NodeJS.ProcessEnv): string {
  const join = platform === 'win32' ? path.win32.join : path.posix.join;
  return join(configDir(platform, home, env), 'launchers');
}

function fileName(game: Game, platform: NodeJS.Platform): string {
  const safe = `${game.store}-${game.id}`.replace(/[^A-Za-z0-9._-]+/g, '_');
  return `${safe}.${platform === 'win32' ? 'ps1' : 'sh'}`;
}

function assertSafe(value: string, what: string, forbidden: RegExp): void {
  if (forbidden.test(value)) throw new Error(`Refusing to put unsafe ${what} into a launcher script: ${value}`);
}

type UriGame = Game & { launch: UriLaunch };

/** Puts a game's processes into a Windows job object that ends them when it closes, so Steam's Stop ends the game too. */
const JOB_SOURCE = `using System;
using System.Runtime.InteropServices;
public static class SteamManagerJob {
  [DllImport("kernel32.dll", CharSet = CharSet.Unicode)] static extern IntPtr CreateJobObject(IntPtr attributes, string name);
  [DllImport("kernel32.dll")] static extern bool SetInformationJobObject(IntPtr job, int infoClass, IntPtr info, int size);
  [DllImport("kernel32.dll")] static extern bool AssignProcessToJobObject(IntPtr job, IntPtr process);
  public static IntPtr Create() {
    IntPtr job = CreateJobObject(IntPtr.Zero, null);
    int size = IntPtr.Size == 8 ? 144 : 112; // JOBOBJECT_EXTENDED_LIMIT_INFORMATION
    IntPtr info = Marshal.AllocHGlobal(size);
    try {
      for (int i = 0; i < size; i++) Marshal.WriteByte(info, i, 0);
      Marshal.WriteInt32(info, 16, 0x2000); // LimitFlags: kill the processes when the job is closed
      SetInformationJobObject(job, 9, info, size);
    } finally {
      Marshal.FreeHGlobal(info);
    }
    return job;
  }
  public static bool Assign(IntPtr job, IntPtr process) { return AssignProcessToJobObject(job, process); }
}`;

/** A value inside a single-quoted PowerShell string. */
function psQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function psScript(game: UriGame): string {
  const { uri, waitFor, installDir } = game.launch;
  assertSafe(uri, 'URI', /[\r\n]/);
  const lines = [`# Generated by steam-manager for ${game.title.replace(/[\r\n]/g, ' ')}`, `Start-Process -FilePath ${psQuote(uri)}`];
  if (installDir === undefined && waitFor === undefined) return `${lines.join('\r\n')}\r\n`;
  if (installDir !== undefined) assertSafe(installDir, 'install folder', /[\r\n]/);
  if (waitFor !== undefined) assertSafe(waitFor, 'process name', /[^\w .()-]/);
  return `${[
    lines[0],
    '# Starts the game through its launcher and stays alive while it runs, so Steam shows it as running.',
    "# Steam's Stop ends this script; the job object then ends the game too.",
    "$ErrorActionPreference = 'SilentlyContinue'",
    `$prefix = ${installDir === undefined ? '$null' : psQuote(`${installDir.replace(/[\\/]+$/, '')}\\`)}`,
    `$name = ${waitFor === undefined ? '$null' : psQuote(waitFor)}`,
    "Add-Type -TypeDefinition @'",
    JOB_SOURCE,
    "'@",
    lines[1],
    '$job = [SteamManagerJob]::Create()',
    'function Get-GameProcesses {',
    '  $all = Get-CimInstance -ClassName Win32_Process',
    '  if ($prefix) { $all | Where-Object { $_.ExecutablePath -and $_.ExecutablePath.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase) } }',
    '  elseif ($name) { $all | Where-Object { $_.Name -eq $name } }',
    '}',
    '$seen = @{}',
    '$started = $false',
    '$gone = 0',
    `$deadline = (Get-Date).AddSeconds(${MAX_WAIT_SECONDS})`,
    'while ($true) {',
    '  $running = @(Get-GameProcesses)',
    '  foreach ($game in $running) {',
    '    if (-not $seen.ContainsKey($game.ProcessId)) {',
    '      $seen[$game.ProcessId] = $true',
    '      $handle = (Get-Process -Id $game.ProcessId).Handle',
    '      if ($handle) { [void][SteamManagerJob]::Assign($job, $handle) }',
    '    }',
    '  }',
    '  if ($running.Count -gt 0) { $started = $true; $gone = 0 }',
    '  elseif ($started) { $gone++; if ($gone -ge 3) { break } }',
    '  elseif ((Get-Date) -gt $deadline) { break }',
    '  Start-Sleep -Seconds 2',
    '}',
  ].join('\r\n')}\r\n`;
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function shScript(platform: NodeJS.Platform, game: UriGame): string {
  const { uri, waitFor } = game.launch;
  assertSafe(uri, 'URI', /[\r\n]/);
  const opener = platform === 'darwin' ? 'open' : 'xdg-open';
  const lines = ['#!/bin/sh', `# Generated by steam-manager for ${game.title.replace(/[\r\n]/g, ' ')}`, `${opener} ${shellQuote(uri)}`];
  if (waitFor !== undefined) {
    assertSafe(waitFor, 'process name', /[\r\n]/);
    // pgrep -x matches at most 15 characters of the process name
    const name = shellQuote(waitFor.slice(0, 15));
    lines.push(
      'tries=0',
      `while [ "$tries" -lt ${MAX_WAIT_SECONDS} ]; do`,
      `  pgrep -x ${name} >/dev/null && break`,
      '  tries=$((tries + 1))',
      '  sleep 1',
      'done',
      `while pgrep -x ${name} >/dev/null; do sleep 5; done`,
    );
  }
  return `${lines.join('\n')}\n`;
}

/** The text of the wrapper script for a URI launch on a platform. */
export function renderWrapper(platform: NodeJS.Platform, game: UriGame): string {
  return platform === 'win32' ? psScript(game) : shScript(platform, game);
}

export interface ResolveOptions {
  platform: NodeJS.Platform;
  /** Directory for wrapper scripts (see `wrapperDir`). */
  dir: string;
  /** When false (dry runs) the path is computed but nothing is written. */
  write: boolean;
  /** Windows: run the script without a console window through `conhost --headless` (default), else with a hidden window. */
  headless?: boolean;
  /** Windows folder, for the paths of conhost and PowerShell (default `C:\Windows`). */
  systemRoot?: string;
}

/** Windows: what Steam should run so that a PowerShell script runs in the background. */
function windowsTarget(script: string, options: ResolveOptions): { exe: string; launchOptions: string } {
  const root = options.systemRoot ?? 'C:\\Windows';
  const powershell = path.win32.join(root, 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
  const run = `-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${script}"`;
  if (options.headless === false) return { exe: powershell, launchOptions: `-WindowStyle Hidden ${run}` };
  return { exe: path.win32.join(root, 'System32', 'conhost.exe'), launchOptions: `--headless "${powershell}" ${run}` };
}

/** Turns a game's launch spec into what a Steam shortcut can run, generating a wrapper for URIs. */
export async function resolveTarget(game: Game, options: ResolveOptions): Promise<ShortcutTarget> {
  const { launch } = game;
  if (launch.kind === 'exe') {
    return { exe: launch.exe, startDir: launch.startDir, launchOptions: launch.args };
  }
  const uriGame = { ...game, launch };
  const script = path.join(options.dir, fileName(game, options.platform));
  if (options.write) {
    const content = renderWrapper(options.platform, uriGame);
    await mkdir(options.dir, { recursive: true });
    await writeFile(script, content);
    if (options.platform !== 'win32') await chmod(script, 0o755);
  }
  if (options.platform === 'win32') return { ...windowsTarget(script, options), startDir: options.dir };
  return { exe: script, startDir: options.dir };
}
