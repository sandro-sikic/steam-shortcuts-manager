import { execFileSync } from 'node:child_process';
import { chmod, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { renderWrapper, resolveTarget, wrapperDir } from '../src/launcher/wrapper.js';
import type { Game, UriLaunch } from '../src/types.js';
import { cleanupTempDirs, makeTempDir } from './helpers.js';

afterEach(cleanupTempDirs);

const uriGame = (uri: string, waitFor?: string, over: Partial<Game> = {}): Game => ({
  store: 'Ubisoft Connect',
  id: 'a/b 1',
  title: 'Anno 1800',
  installed: true,
  launch: { kind: 'uri', uri, waitFor },
  ...over,
});

describe('wrapperDir', () => {
  it('follows each platform convention', () => {
    expect(wrapperDir('win32', 'C:\\Users\\h', { APPDATA: 'D:\\Roaming' })).toBe('D:\\Roaming\\steam-manager\\launchers');
    expect(wrapperDir('win32', 'C:\\Users\\h', {})).toBe('C:\\Users\\h\\AppData\\Roaming\\steam-manager\\launchers');
    expect(wrapperDir('darwin', '/Users/h', {})).toBe('/Users/h/Library/Application Support/steam-manager/launchers');
    expect(wrapperDir('linux', '/h', { XDG_CONFIG_HOME: '/x' })).toBe('/x/steam-manager/launchers');
    expect(wrapperDir('linux', '/h', {})).toBe('/h/.config/steam-manager/launchers');
  });
});

describe('resolveTarget', () => {
  it('passes executables straight through', async () => {
    const game: Game = { store: 's', id: 'i', title: 't', installed: true, launch: { kind: 'exe', exe: '/e', startDir: '/d', args: '-x' } };
    expect(await resolveTarget(game, { platform: 'linux', dir: '/unused', write: true })).toEqual({ exe: '/e', startDir: '/d', launchOptions: '-x' });
  });

  it('writes an executable POSIX script with a sanitized name', async () => {
    const dir = await makeTempDir();
    const target = await resolveTarget(uriGame("heroic://launch/it's"), { platform: 'linux', dir, write: true });
    expect(target).toEqual({ exe: path.join(dir, 'Ubisoft_Connect-a_b_1.sh'), startDir: dir });
    const content = await readFile(target.exe, 'utf8');
    expect(content).toBe(`#!/bin/sh\n# Generated by steam-manager for Anno 1800\nxdg-open 'heroic://launch/it'\\''s'\n`);
    expect((await stat(target.exe)).mode & 0o111).not.toBe(0);
    if (process.platform !== 'win32') execFileSync('sh', ['-n', target.exe]);
  });

  it('uses `open` on macOS and waits for the game process (truncated for pgrep -x)', async () => {
    const dir = await makeTempDir();
    const target = await resolveTarget(uriGame('x://y', 'AVeryLongProcessName.exe'), { platform: 'darwin', dir, write: true });
    const content = await readFile(target.exe, 'utf8');
    expect(content).toContain("open 'x://y'");
    expect(content).toContain("pgrep -x 'AVeryLongProces' >/dev/null && break");
    expect(content).toContain("while pgrep -x 'AVeryLongProces' >/dev/null; do sleep 5; done");
    if (process.platform !== 'win32') execFileSync('sh', ['-n', target.exe]);
  });

  it('really runs the POSIX script (stubbed opener)', async () => {
    if (process.platform === 'win32') return;
    const dir = await makeTempDir();
    const bin = await makeTempDir();
    const out = path.join(bin, 'out');
    await writeFile(path.join(bin, 'xdg-open'), `#!/bin/sh\necho "$1" > '${out}'\n`);
    await chmod(path.join(bin, 'xdg-open'), 0o755);
    const target = await resolveTarget(uriGame('uplay://launch/1/0'), { platform: 'linux', dir, write: true });
    execFileSync('sh', [target.exe], { env: { ...process.env, PATH: `${bin}:${process.env['PATH']}` } });
    expect((await readFile(out, 'utf8')).trim()).toBe('uplay://launch/1/0');
  });

  it('runs a Windows PowerShell script through conhost without a window, and keeps Steam pointed at it', async () => {
    const dir = await makeTempDir();
    const target = await resolveTarget(uriGame('uplay://launch/1/0'), { platform: 'win32', dir, write: true, systemRoot: 'D:\\Win' });
    const script = path.join(dir, 'Ubisoft_Connect-a_b_1.ps1');
    expect(target).toEqual({
      exe: 'D:\\Win\\System32\\conhost.exe',
      launchOptions: `--headless "D:\\Win\\System32\\WindowsPowerShell\\v1.0\\powershell.exe" -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${script}"`,
      startDir: dir,
    });
    expect(await readFile(script, 'utf8')).toBe("# Generated by steam-manager for Anno 1800\r\nStart-Process -FilePath 'uplay://launch/1/0'\r\n");
  });

  it('can run PowerShell with a hidden window instead, and defaults to the usual Windows folder', async () => {
    const dir = await makeTempDir();
    const target = await resolveTarget(uriGame('x://y'), { platform: 'win32', dir, write: false, headless: false });
    expect(target.exe).toBe('C:\\Windows\\System32\\WindowsPowerShell\\v1.0\\powershell.exe');
    expect(target.launchOptions).toBe(`-WindowStyle Hidden -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${path.join(dir, 'Ubisoft_Connect-a_b_1.ps1')}"`);
    const headless = await resolveTarget(uriGame('x://y'), { platform: 'win32', dir, write: false });
    expect(headless.exe).toBe('C:\\Windows\\System32\\conhost.exe');
  });

  it("starts a Windows launcher URI with quotes in it safely", () => {
    const game = uriGame("x://y?a=100%&b='c'") as Game & { launch: UriLaunch };
    expect(renderWrapper('win32', game)).toBe("# Generated by steam-manager for Anno 1800\r\nStart-Process -FilePath 'x://y?a=100%&b=''c'''\r\n");
  });

  describe('Windows supervisor script', () => {
    const script = (launch: Partial<UriLaunch>, title = 'Anno 1800') =>
      renderWrapper('win32', uriGame('x://y', undefined, { title, launch: { kind: 'uri', uri: 'x://y', ...launch } }) as Game & { launch: UriLaunch }).split('\r\n');

    it('watches the install folder, and ends the game with the script through a job object', () => {
      const lines = script({ installDir: 'C:\\Program Files\\Epic Games\\Auto\'mation\\', waitFor: 'Auto.exe' });
      expect(lines).toContain("$prefix = 'C:\\Program Files\\Epic Games\\Auto''mation\\'");
      expect(lines).toContain("$name = 'Auto.exe'");
      expect(lines).toContain("Add-Type -TypeDefinition @'");
      expect(lines.join('\n')).toContain('Marshal.WriteInt32(info, 16, 0x2000)');
      expect(lines).toContain('$job = [SteamManagerJob]::Create()');
      expect(lines).toContain('      if ($handle) { [void][SteamManagerJob]::Assign($job, $handle) }');
      expect(lines).toContain('$deadline = (Get-Date).AddSeconds(120)');
      expect(lines).toContain('  elseif ($started) { $gone++; if ($gone -ge 3) { break } }');
      expect(lines.indexOf("Start-Process -FilePath 'x://y'")).toBeGreaterThan(lines.indexOf("'@"));
    });

    it('adds the missing trailing backslash to a folder, once', () => {
      expect(script({ installDir: 'D:\\Games\\A' })).toContain("$prefix = 'D:\\Games\\A\\'");
      expect(script({ installDir: 'D:\\Games\\A\\\\' })).toContain("$prefix = 'D:\\Games\\A\\'");
      expect(script({ installDir: 'D:/Games/A/' })).toContain("$prefix = 'D:/Games/A\\'");
    });

    it('can wait by process name alone, or by folder alone', () => {
      expect(script({ waitFor: 'Anno 1800 (x64).exe' })).toEqual(expect.arrayContaining(['$prefix = $null', "$name = 'Anno 1800 (x64).exe'"]));
      expect(script({ installDir: 'D:\\A' })).toContain('$name = $null');
    });

    it('only starts the URI when there is nothing to wait for', () => {
      expect(script({})).toEqual(['# Generated by steam-manager for Anno 1800', "Start-Process -FilePath 'x://y'", '']);
    });

    it('keeps a title with line breaks on one comment line', () => {
      expect(script({ waitFor: 'a.exe' }, 'Two\nLines')[0]).toBe('# Generated by steam-manager for Two Lines');
    });
  });

  it('does not touch the disk when write is false', async () => {
    const dir = path.join(await makeTempDir(), 'missing');
    const target = await resolveTarget(uriGame('x://y'), { platform: 'linux', dir, write: false });
    await expect(stat(target.exe)).rejects.toThrow();
  });

  it('refuses to embed unsafe values', async () => {
    const dir = await makeTempDir();
    await expect(resolveTarget(uriGame('x://y\r\ncalc'), { platform: 'win32', dir, write: true })).rejects.toThrow('unsafe URI');
    await expect(resolveTarget(uriGame('x://y', 'a&b.exe'), { platform: 'win32', dir, write: true })).rejects.toThrow('unsafe process name');
    await expect(resolveTarget(uriGame('x://y', undefined, { launch: { kind: 'uri', uri: 'x://y', installDir: 'C:\\a\nb' } }), { platform: 'win32', dir, write: true })).rejects.toThrow('unsafe install folder');
    await expect(resolveTarget(uriGame('x://y\nrm -rf /'), { platform: 'linux', dir, write: true })).rejects.toThrow('unsafe URI');
    await expect(resolveTarget(uriGame('x://y', 'a\nb'), { platform: 'linux', dir, write: true })).rejects.toThrow('unsafe process name');
  });
});
