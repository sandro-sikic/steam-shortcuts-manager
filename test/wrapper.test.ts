import { execFileSync } from 'node:child_process';
import { chmod, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { renderWrapper, resolveTarget, wrapperDir } from '../src/launcher/wrapper.js';
import type { Game, UriLaunch } from '../src/types.js';
import { cleanupTempDirs, makeTempDir } from './helpers.js';

afterEach(cleanupTempDirs);

const uriGame = (uri: string, waitFor?: string, over: Partial<Game> = {}): Game => ({
  store: 'Ubisoft Connect',
  id: 'a/b 1',
  title: 'Anno 1800',
  installed: true,
  launch: { kind: 'uri', uri, waitFor },
  ...over,
});

describe('wrapperDir', () => {
  it('follows each platform convention', () => {
    expect(wrapperDir('win32', 'C:\\Users\\h', { APPDATA: 'D:\\Roaming' })).toBe('D:\\Roaming\\steam-manager\\launchers');
    expect(wrapperDir('win32', 'C:\\Users\\h', {})).toBe('C:\\Users\\h\\AppData\\Roaming\\steam-manager\\launchers');
    expect(wrapperDir('darwin', '/Users/h', {})).toBe('/Users/h/Library/Application Support/steam-manager/launchers');
    expect(wrapperDir('linux', '/h', { XDG_CONFIG_HOME: '/x' })).toBe('/x/steam-manager/launchers');
    expect(wrapperDir('linux', '/h', {})).toBe('/h/.config/steam-manager/launchers');
  });
});

describe('resolveTarget', () => {
  it('passes executables straight through', async () => {
    const game: Game = { store: 's', id: 'i', title: 't', installed: true, launch: { kind: 'exe', exe: '/e', startDir: '/d', args: '-x' } };
    expect(await resolveTarget(game, { platform: 'linux', dir: '/unused', write: true })).toEqual({ exe: '/e', startDir: '/d', launchOptions: '-x' });
  });

  it('writes an executable POSIX script with a sanitized name', async () => {
    const dir = await makeTempDir();
    const target = await resolveTarget(uriGame("heroic://launch/it's"), { platform: 'linux', dir, write: true });
    expect(target).toEqual({ exe: path.join(dir, 'Ubisoft_Connect-a_b_1.sh'), startDir: dir });
    const content = await readFile(target.exe, 'utf8');
    expect(content).toBe(`#!/bin/sh\n# Generated by steam-manager for Anno 1800\nxdg-open 'heroic://launch/it'\\''s'\n`);
    expect((await stat(target.exe)).mode & 0o111).not.toBe(0);
    if (process.platform !== 'win32') execFileSync('sh', ['-n', target.exe]);
  });

  it('uses `open` on macOS and waits for the game process (truncated for pgrep -x)', async () => {
    const dir = await makeTempDir();
    const target = await resolveTarget(uriGame('x://y', 'AVeryLongProcessName.exe'), { platform: 'darwin', dir, write: true });
    const content = await readFile(target.exe, 'utf8');
    expect(content).toContain("open 'x://y'");
    expect(content).toContain("pgrep -x 'AVeryLongProces' >/dev/null && break");
    expect(content).toContain("while pgrep -x 'AVeryLongProces' >/dev/null; do sleep 5; done");
    if (process.platform !== 'win32') execFileSync('sh', ['-n', target.exe]);
  });

  it('really runs the POSIX script (stubbed opener)', async () => {
    if (process.platform === 'win32') return;
    const dir = await makeTempDir();
    const bin = await makeTempDir();
    const out = path.join(bin, 'out');
    await writeFile(path.join(bin, 'xdg-open'), `#!/bin/sh\necho "$1" > '${out}'\n`);
    await chmod(path.join(bin, 'xdg-open'), 0o755);
    const target = await resolveTarget(uriGame('uplay://launch/1/0'), { platform: 'linux', dir, write: true });
    execFileSync('sh', [target.exe], { env: { ...process.env, PATH: `${bin}:${process.env['PATH']}` } });
    expect((await readFile(out, 'utf8')).trim()).toBe('uplay://launch/1/0');
  });

  it('writes Windows wrappers as .cmd files (no chmod)', async () => {
    const dir = await makeTempDir();
    const target = await resolveTarget(uriGame('uplay://launch/1/0'), { platform: 'win32', dir, write: true });
    expect(target).toEqual({ exe: path.join(dir, 'Ubisoft_Connect-a_b_1.cmd'), startDir: dir });
    expect(await readFile(target.exe, 'utf8')).toContain('start "" "uplay://launch/1/0"');
  });

  it('renders a Windows .cmd that starts the URI and escapes %', () => {
    const game = uriGame('uplay://launch/1/0?a=100%') as Game & { launch: UriLaunch };
    expect(renderWrapper('win32', game)).toBe(
      '@echo off\r\nrem Generated by steam-manager for Anno 1800\r\nstart "" "uplay://launch/1/0?a=100%%"\r\n',
    );
  });

  it('renders a Windows .cmd that waits for the game process', () => {
    const game = uriGame('x://y', 'Anno 1800 (x64).exe') as Game & { launch: UriLaunch };
    const lines = renderWrapper('win32', game).split('\r\n');
    expect(lines).toContain('tasklist /FI "IMAGENAME eq Anno 1800 (x64).exe" /NH | find /I "Anno 1800 (x64).exe" >nul && goto running');
    expect(lines).toContain('if %tries% GEQ 120 exit /b 0');
    expect(lines.at(-2)).toBe('exit /b 0');
  });

  it('does not touch the disk when write is false', async () => {
    const dir = path.join(await makeTempDir(), 'missing');
    const target = await resolveTarget(uriGame('x://y'), { platform: 'linux', dir, write: false });
    await expect(stat(target.exe)).rejects.toThrow();
  });

  it('refuses to embed unsafe values', async () => {
    const dir = await makeTempDir();
    await expect(resolveTarget(uriGame('x://y"&calc'), { platform: 'win32', dir, write: true })).rejects.toThrow('unsafe URI');
    await expect(resolveTarget(uriGame('x://y', 'a&b.exe'), { platform: 'win32', dir, write: true })).rejects.toThrow('unsafe process name');
    await expect(resolveTarget(uriGame('x://y\nrm -rf /'), { platform: 'linux', dir, write: true })).rejects.toThrow('unsafe URI');
    await expect(resolveTarget(uriGame('x://y', 'a\nb'), { platform: 'linux', dir, write: true })).rejects.toThrow('unsafe process name');
  });
});
